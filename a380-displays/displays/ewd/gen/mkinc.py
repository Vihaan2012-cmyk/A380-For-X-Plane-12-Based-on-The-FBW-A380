import json, sys
d = json.load(open(sys.argv[1]))
keep = {k: d[k] for k in ['EcamMemos', 'EcamLimitations', 'EcamInfos', 'EcamAbnormalSensedProcedures', 'EcamDeferredProcedures', 'EcamNormalProcedures', 'deferredProcedureIds']}
b = json.dumps(keep, separators=(',', ':'), ensure_ascii=True).encode()
with open(sys.argv[2], 'w') as f:
    f.write('// generated by gen/extract.js + gen/mkinc.py from FlyByWire EcamMessages\n')
    f.write('static const unsigned char kEcamJson[] = {\n')
    for i in range(0, len(b), 32):
        f.write(','.join(str(x) for x in b[i:i+32]) + ',\n')
    f.write('0};\n')
print(len(b))
