import re
import sys

SRC = sys.argv[1]
OUT = sys.argv[2]

text = open(SRC, encoding="utf-8").read()
dl_start = text.index("export const CpdlcMessagesDownlink")
ul_start = text.index("export const CpdlcMessagesUplink")
tables = {"DOWNLINK": text[dl_start:ul_start], "UPLINK": text[ul_start:]}

RESP = {
    "NotRequired": "NotRequired",
    "WilcoUnable": "WilcoUnable",
    "AffirmNegative": "AffirmNegative",
    "Roger": "Roger",
    "No": "No",
    "Yes": "Yes",
}


def parse_args(raw):
    idx = []
    mon = False
    val = ""
    for part in [p.strip() for p in raw.split(",") if p.strip()]:
        if part in ("true", "false"):
            mon = part == "true"
        elif part.startswith("'"):
            val = part.strip("'")
        else:
            idx.append(int(part))
    start = idx[0] if len(idx) > 0 else -1
    end = idx[1] if len(idx) > 1 else -1
    return start, end, mon, val


def parse_table(body):
    keys = list(re.finditer(r"^  ((?:DM|UM)\d+): \[", body, re.M))
    entries = []
    for i, m in enumerate(keys):
        end = keys[i + 1].start() if i + 1 < len(keys) else len(body)
        seg = body[m.end():end]
        key = m.group(1)
        first = seg.index("]")
        templates = re.findall(r"'((?:[^'\\]|\\.)*)'", seg[:first])
        elem = seg[seg.index("new CpdlcMessageElement("):]
        type_id = re.search(r"CpdlcMessageElement\(\s*'([^']+)'", elem).group(1)
        assert type_id == key, (type_id, key)
        fans = re.findall(r"FansMode\.(Fans[AB])", elem)
        contents = []
        for c in re.finditer(r"new CpdlcMessageContent(\w+)\(([^)]*)\)", elem):
            contents.append((c.group(1),) + parse_args(c.group(2)))
        stripped = re.sub(r"new CpdlcMessageContent\w+\([^)]*\)", "", elem)
        urgent = re.search(r"^\s*true,\s*$", stripped, re.M) is not None
        r = re.search(r"CpdlcMessageExpectedResponseType\.(\w+)", elem)
        resp = RESP[r.group(1)] if r else "No"
        entries.append((key, templates, fans, urgent, resp, contents))
    return entries


def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = []
out.append("// Generated by tools/gen_catalogue.py from FlyByWire's CpdlcMessageElements.ts (GPL-3.0).")
out.append("use crate::elements::{ContentDef, ContentType, ElementDef, ExpectedResponse};")
out.append("use crate::fans::FansMode::{FansA, FansB};")
out.append("")
for name, body in tables.items():
    entries = parse_table(body)
    out.append(f"pub static {name}: &[ElementDef] = &[")
    for key, templates, fans, urgent, resp, contents in entries:
        out.append("    ElementDef {")
        out.append(f"        type_id: {rs_str(key)},")
        out.append("        templates: &[" + ", ".join(rs_str(t) for t in templates) + "],")
        out.append("        fans: &[" + ", ".join(fans) + "],")
        out.append(f"        urgent: {'true' if urgent else 'false'},")
        out.append(f"        response: ExpectedResponse::{resp},")
        if contents:
            out.append("        content: &[")
            for kind, s, e, mon, val in contents:
                out.append(
                    f"            ContentDef {{ kind: ContentType::{kind}, index_start: {s}, index_end: {e}, monitoring: {'true' if mon else 'false'}, value: {rs_str(val)} }},"
                )
            out.append("        ],")
        else:
            out.append("        content: &[],")
        out.append("    },")
    out.append("];")
    out.append("")
    print(name, len(entries), file=sys.stderr)

open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
