import re
import sys

ROOT = sys.argv[1]
OUT = sys.argv[2]

fans_src = open(f"{ROOT}/common/src/com/FutureAirNavigationSystem.ts", encoding="utf-8").read()
start = fans_src.index("areasFansB = [")
end = fans_src.index("];", start)
areas = re.findall(r"'([0-9A-Z]{4})'", fans_src[start:end])

groups = [
    ("ATC_TO_FMS", "atc/src/databus/FmsBus.ts", "AtcFmsMessages"),
    ("FMS_TO_ATC", "atc/src/databus/FmsBus.ts", "FmsAtcMessages"),
    ("ROUTER_TO_FMS", "router/src/databus/FmsBus.ts", "RouterFmsMessages"),
    ("FMS_TO_ROUTER", "router/src/databus/FmsBus.ts", "FmsRouterMessages"),
    ("AOC_TO_FMS", "aoc/src/databus/FmsBus.ts", "AocFmsMessages"),
    ("FMS_TO_AOC", "aoc/src/databus/FmsBus.ts", "FmsAocMessages"),
    ("ATC_AOC_TO_ROUTER", "router/src/databus/AtcAocBus.ts", "AtcAocRouterMessages"),
    ("ROUTER_TO_ATC_AOC", "router/src/databus/AtcAocBus.ts", "RouterAtcAocMessages"),
    ("MAILBOX", "common/src/databus/Mailbox.ts", "AtsuMailboxMessages"),
    ("MESSAGE_BUTTON", "atc/src/databus/AtcMessageButtonBus.ts", "AtcMessageButtonBusMessages"),
]


def members(path, iface):
    text = open(f"{ROOT}/{path}", encoding="utf-8").read()
    i = text.index(f"export interface {iface}")
    j = text.index("\n}", i)
    body = text[text.index("{", i) + 1:j]
    names = []
    depth = 0
    for line in body.split("\n"):
        stripped = line.strip()
        if depth == 0:
            m = re.match(r"^([A-Za-z0-9_]+)\??:", stripped)
            if m:
                names.append(m.group(1))
        depth += stripped.count("{") - stripped.count("}")
    return names


out = ["// Generated by tools/gen_tables.py from FlyByWire's datalink sources (GPL-3.0).", ""]
out.append("pub static FANS_B_AREAS: &[&str] = &[")
for k in range(0, len(areas), 8):
    out.append("    " + ", ".join(f'"{a}"' for a in areas[k:k + 8]) + ",")
out.append("];")
out.append("")
total = 0
for name, path, iface in groups:
    names = members(path, iface)
    total += len(names)
    out.append(f"pub static {name}: &[&str] = &[")
    for n in names:
        out.append(f'    "{n}",')
    out.append("];")
    out.append("")
    print(name, len(names), file=sys.stderr)
print("topics", total, "areas", len(areas), file=sys.stderr)
out.append("pub static ALL_GROUPS: &[(&str, &[&str])] = &[")
for name, _, _ in groups:
    out.append(f'    ("{name}", {name}),')
out.append("];")
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
