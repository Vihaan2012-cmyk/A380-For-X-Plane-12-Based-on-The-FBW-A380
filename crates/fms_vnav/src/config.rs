#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum FlapConf {
    Clean = 0,
    Conf1 = 1,
    Conf2 = 2,
    Conf3 = 3,
    ConfFull = 4,
}

pub type Table = Vec<Vec<f64>>;

#[derive(Clone, Debug)]
pub struct FlightModelParameters {
    pub wing_span: f64,
    pub wing_area: f64,
    pub wing_effcy_factor: f64,
    pub required_accel_rate_kns: f64,
    pub required_accel_rate_ms2: f64,
    pub gravity_const_kns: f64,
    pub gravity_const_ms2: f64,
    pub mach_values: Vec<f64>,
    pub drag_coefficient_corrections: Vec<f64>,
    pub speed_brake_drag: f64,
    pub gear_drag: f64,
    pub drag_polar_coefficients: [Vec<f64>; 5],
}

#[derive(Clone, Debug)]
pub struct EngineModelParameters {
    pub max_thrust: f64,
    pub number_of_engines: f64,
    pub fuel_burn_factor: f64,
    pub cn1_climb_limit: Table,
    pub table1502: Table,
    pub table1503: Table,
    pub table1504: Table,
    pub table1506: Table,
}

#[derive(Clone, Debug)]
pub struct VnavConfig {
    pub idle_n1_margin: f64,
    pub maximum_fuel_estimate: f64,
    pub lowest_fuel_estimate: f64,
    pub vmo: f64,
    pub mmo: f64,
    pub emit_cda_flap_pwp: bool,
    pub use_latched_descent_mode: bool,
}

#[derive(Clone, Debug)]
pub struct AircraftConfig {
    pub vnav: VnavConfig,
    pub engine: EngineModelParameters,
    pub flight: FlightModelParameters,
}

fn t(rows: &[&[f64]]) -> Table {
    rows.iter().map(|r| r.to_vec()).collect()
}

