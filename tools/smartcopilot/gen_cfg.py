"""Write smartcopilot.cfg from sync_list.json (see derive_list.py).

    python tools/smartcopilot/gen_cfg.py tools/smartcopilot/sync_list.json \
        --out E:/fbw-build/smartcopilot/smartcopilot.cfg
"""

import argparse
import json
import sys
from pathlib import Path

ORDER = ["TRIGGERS", "CONTINUED", "SEND_BACK", "COMMANDS", "OVERRIDE", "SLOW", "WEATHER", "TRANSPONDER", "RADIO"]
VALID = set(ORDER) | {"CLICKS"}
INFO_MAX = 20


def render(data):
    by_section = {}
    seen = set()
    for e in data["entries"]:
        s = e["section"]
        if s not in VALID:
            raise SystemExit(f"unknown section {s}")
        key = (s, e["name"])
        if key in seen:
            continue
        seen.add(key)
        by_section.setdefault(s, []).append(e)
    owner = {}
    for s in ("TRIGGERS", "CONTINUED", "SEND_BACK", "SLOW"):
        for e in by_section.get(s, []):
            if e["name"] in owner:
                raise SystemExit(f"{e['name']} in both {owner[e['name']]} and {s}")
            owner[e["name"]] = s
    out = ["## A380 for X-Plane 12 -- SmartCopilot configuration", "## Generated by tools/smartcopilot/gen_cfg.py; edit sync_list.json, not this file.", ""]
    out.append("[SETUP]")
    out += [f"{k} = {v}" for k, v in data.get("setup", {}).items()]
    out.append("")
    for s in ORDER + sorted(VALID - set(ORDER)):
        rows = by_section.get(s)
        if rows is None and s not in ("WEATHER", "TRANSPONDER", "RADIO"):
            continue
        out.append(f"[{s}]")
        last = None
        for e in rows or []:
            if e.get("source") != last:
                out.append(f"# {e.get('source', '')}")
                last = e.get("source")
            out.append(f"{e['name']} = {e['value']}")
        out.append("")
    out.append("[INFO]")
    for k, v in data.get("info", {}).items():
        if len(str(v)) > INFO_MAX:
            raise SystemExit(f"INFO {k} longer than {INFO_MAX} characters")
        out.append(f"{k} = {v}")
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("sync_list")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    data = json.loads(Path(a.sync_list).read_text(encoding="utf-8"))
    text = render(data)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_bytes(text.replace("\n", "\r\n").encode("ascii"))
    counts = {}
    for e in data["entries"]:
        counts[e["section"]] = counts.get(e["section"], 0) + 1
    print(a.out, counts)
    return 0


if __name__ == "__main__":
    sys.exit(main())
