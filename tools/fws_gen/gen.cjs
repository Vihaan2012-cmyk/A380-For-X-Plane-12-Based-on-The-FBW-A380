function bareField(node, ctx) {
  const n = strip(node);
  if (!ts.isPropertyAccessExpression(n)) return null;
  const m = memberChain(n, ctx);
  return m && m.member && fields.has(m.member) ? fields.get(m.member).rust : null;
}

