function coerce(r, kind, node) {
  switch (kind) {
    case 'bool':
      return toBool(r);
    case 'num':
      if (r.type === 'optnum') return `${r.code}.unwrap_or(0.0)`;
      return toNum(r);
    case 'optnum':
      if (r.type === 'num') return `Some(${r.code})`;
      if (r.type === 'optnum') return r.code;
      if (r.type === 'null' || r.type === 'undef') return 'None';
      break;
    case 'word':
      if (r.type === 'word') return r.code;
      break;
  }
  fail(node, `coerce ${r.type} to ${kind}`);
}

const RUST_TY = { bool: 'bool', num: 'f64', optnum: 'Option<f64>' };

function genMapped() {
  let out = HEADER + '#![allow(clippy::all, unused_parens, unused_variables, unused_braces, unused_imports)]\n';
  out += 'use crate::arinc::Word;\nuse crate::fwc::Core;\nuse crate::js::{js_round, J};\n\nimpl Core {\n';
  for (const m of coreClass.members) {
    if (!ts.isPropertyDeclaration(m) || !m.initializer) continue;
    const name = propName(m);
    if (!methods.has(name) || methods.get(name).alias) continue;
    const ty = METHOD_TYPES[name] || 'bool';
    const ctx = new Ctx('core');
    const code = translate(`mapped ${name}`, m.initializer, ctx, (n, c) => {
      const r = coerce(emit(n, c), ty, n);
      if (c.usesV) fail(n, 'mapped subject reads a simvar');
      return r;
    });
    const rust = methods.get(name).rust;
    out += `    pub fn ${rust}(&self) -> ${RUST_TY[ty]} {\n        let c = self;\n        ${code === null ? `crate::hand::mapped_${rust}(c)` : code}\n    }\n\n`;
  }
  return out.replace(/\n\n$/, '\n') + '}\n';
}

const STMT_HOOKS = {
  'this.fuelingTarget.pause()': '',
  'this.fuelingInitiated.pause()': '',
  'this.fuelingTarget.resume()': '',
  'this.fuelingInitiated.resume()': '',
  'this.healthInjector()': 'c.health_injector()',
  'this.flightPhases.update(deltaTime)': 'c.flight_phases_update(v, dt)',
  'this.soundManager.onUpdate(deltaTime)': 'c.sound_on_update(dt)',
};

function wordArg(node, ctx) {
  const n = strip(node);
  if (ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n)) {
    ctx.markV();
    return `Word::from_simvar(v.get(${JSON.stringify(n.text)}))`;
  }
  if (ts.isTemplateExpression(n)) {
    ctx.markV();
    return `Word::from_simvar(v.get(&${templ(n, ctx)}))`;
  }
  fail(node, 'word simvar name');
}

// Boolean subjects FBW also sets with numbers (`a || SimVar...`): Subject.set compares with ===, so `true` -> `1`
// notifies subscribers; the raw value is kept beside the field for the activation time bookkeeping.
const mixedFields = new Set();

function assignField(code, f, r, e) {
  if (f.kind === 'bool' && (r.type === 'j' || r.type === 'num')) {
    mixedFields.add(f.rust);
    return `{ let x = ${toJ(r)}; ${code} = x.truthy(); c.set_raw("${f.rust}", x) }`;
  }
  if (f.kind === 'bool' && mixedFields.has(f.rust)) return `{ let x = ${toBool(r)}; ${code} = x; c.set_raw("${f.rust}", J::B(x)) }`;
  return `${code} = ${coerce(r, f.kind, e)}`;
}

function exprStmt(node, ctx) {
  const e = strip(node);
  const text = e.getText();
  if (text in STMT_HOOKS) return STMT_HOOKS[text];
  if (ts.isPostfixUnaryExpression(e) || ts.isPrefixUnaryExpression(e)) {
    const o = strip(e.operand);
    if (ts.isIdentifier(o) && ctx.env[o.text] && ctx.env[o.text].local) {
      if (e.operator === ts.SyntaxKind.PlusPlusToken) return `${ctx.env[o.text].code} += 1.0`;
      if (e.operator === ts.SyntaxKind.MinusMinusToken) return `${ctx.env[o.text].code} -= 1.0`;
    }
  }
  if (ts.isCallExpression(e) && strip(e.expression).getText() === 'this.populateCpiomBWords') {
    const a = e.arguments;
    return `c.populate_cpiom_b_words(v, ${toNum(emit(a[5], ctx))} as usize, ${toBool(emit(a[4], ctx))})`;
  }
  if (ts.isCallExpression(e) && /^this\.soundManager\.\w+$/.test(strip(e.expression).getText())) {
    const method = strip(e.expression).name.text;
    const args = e.arguments.map((a) => {
      const n = strip(a);
      if (ts.isStringLiteral(n)) return JSON.stringify(n.text);
      const en = /^FwsAuralVolume\.(\w+)$/.exec(n.getText());
      if (en) return `crate::sound::Volume::${en[1]}`;
      return toBool(emit(n, ctx));
    });
    return `c.sound.${snake(method)}(${args.join(', ')})`;
  }
  if (ts.isBinaryExpression(e) && (e.operatorToken.kind === ts.SyntaxKind.BarBarEqualsToken || e.operatorToken.kind === ts.SyntaxKind.AmpersandAmpersandEqualsToken)) {
    const left = strip(e.left);
    const l = ts.isIdentifier(left) && ctx.env[left.text];
    if (!l || !l.local || l.type !== 'bool') fail(e, 'logical assignment');
    const op = e.operatorToken.kind === ts.SyntaxKind.BarBarEqualsToken ? '||' : '&&';
    return `${l.code} = ${l.code} ${op} ${toBool(emit(e.right, ctx))}`;
  }
  if (ts.isBinaryExpression(e) && e.operatorToken.kind === ts.SyntaxKind.EqualsToken) {
    const left = strip(e.left);
    if (ts.isIdentifier(left) && left.text in ctx.env && ctx.env[left.text].local) {
      const l = ctx.env[left.text];
      return `${l.code} = ${coerce(emit(e.right, ctx), l.type === 'bool' || l.type === 'num' || l.type === 'optnum' || l.type === 'word' ? l.type : 'num', e)}`;
    }
    const m = memberChain(left, ctx);
    if (m && m.member && fields.has(m.member)) return assignField(m.code, fields.get(m.member), emit(e.right, ctx), e);
    fail(e, 'assignment');
  }
  if (ts.isCallExpression(e) && ts.isPropertyAccessExpression(strip(e.expression))) {
    const callee = strip(e.expression);
    const method = callee.name.text;
    if (callee.getText() === 'SimVar.SetSimVarValue') {
      const n = strip(e.arguments[0]);
      if (!ts.isStringLiteral(n)) fail(e, 'dynamic set simvar');
      const val = emit(e.arguments[2], ctx);
      return `c.write_var(${JSON.stringify(n.text)}, ${toNum(val)})`;
    }
    const m = memberChain(strip(callee.expression), ctx);
    if (m && m.member && fields.has(m.member)) {
      const f = fields.get(m.member);
      const args = e.arguments;
      if (method === 'set' && args.length === 1) return assignField(m.code, f, emit(args[0], ctx), e);
      if (f.kind === 'word') {
        if (method === 'setWord') return `${m.code} = Word::from_simvar(${toNum(emit(args[0], ctx))})`;
        if (method === 'setFromSimVar') return `${m.code} = ${wordArg(args[0], ctx)}`;
        if (method === 'setBitValue') return `{ let b = ${toBool(emit(args[1], ctx))}; ${m.code}.set_bit_value(${toNum(emit(args[0], ctx))} as u32, b) }`;
        if (method === 'setSsm') {
          const s = /Arinc429SignStatusMatrix\.(\w+)/.exec(args[0].getText());
          if (s) return `${m.code}.ssm = crate::arinc::Ssm::${s[1]}`;
        }
        if (method === 'setValue') return `{ let x = ${toNum(emit(args[0], ctx))}; ${m.code}.set_value(x) }`;
      }
    }
  }
  const r = emit(e, ctx);
  return r.code;
}

function declare(d, ctx) {
  if (!ts.isIdentifier(d.name)) fail(d, 'declaration');
  const name = `l_${snake(d.name.text)}`;
  const init = d.initializer && strip(d.initializer);
  if (init && ts.isArrowFunction(init)) return ['', { [d.name.text]: { type: 'arrow', fn: init } }];
  let r;
  if (init) {
    r = emit(init, ctx);
    const t = d.type && d.type.getText();
    if (t === 'number | null' && r.type === 'null') r = S('None', 'optnum');
  } else {
    const t = d.type && d.type.getText();
    const DEF = { Arinc429Register: S('Word::empty()', 'word'), number: S('0.0', 'num'), boolean: S('false', 'bool'), 'number | null': S('None', 'optnum') };
    if (!(t in DEF)) fail(d, 'declaration');
    r = DEF[t];
  }
  if (r.type === 'null') fail(d, 'null declaration');
  return [`let mut ${name}: ${{ bool: 'bool', num: 'f64', optnum: 'Option<f64>', word: 'Word' }[r.type] || '_'} = ${r.code};`, { [d.name.text]: { ...S(name, r.type), local: true } }];
}

function stmts(list, ctx) {
  const out = [];
  for (const st of list) {
    if (ts.isVariableStatement(st)) {
      for (const d of st.declarationList.declarations) {
        const [code, env] = declare(d, ctx);
        if (code) out.push(code);
        ctx = ctx.with(env);
      }
    } else out.push(stmt(st, ctx));
  }
  return out.join('\n');
}

function stmt(st, ctx) {
  if (ts.isBlock(st)) return `{\n${stmts(st.statements, ctx)}\n}`;
  if (ts.isIfStatement(st)) {
    const cond = toBool(operand(st.expression, ctx));
    let code = `if ${cond} ${blockOf(st.thenStatement, ctx)}`;
    if (st.elseStatement) code += ` else ${ts.isIfStatement(st.elseStatement) ? stmt(st.elseStatement, ctx) : blockOf(st.elseStatement, ctx)}`;
    return code;
  }
  if (ts.isExpressionStatement(st)) {
    const c = exprStmt(st.expression, ctx);
    return c === '' ? '' : `${c};`;
  }
  if (ts.isReturnStatement(st) && !st.expression) return 'return;';
  fail(st, 'statement');
}

function blockOf(st, ctx) {
  return ts.isBlock(st) ? stmt(st, ctx) : `{\n${stmt(st, ctx)}\n}`;
}

function genUpdate() {
  const list = updateBody.body.statements;
  const i0 = list.findIndex((s) => s.getText().startsWith('if (deltaTime === -1')) + 1;
  const i1 = list.findIndex((s) => s.getText().startsWith('if (this.clrPulseNode.read())'));
  let ctx = new Ctx('core', { deltaTime: S('dt', 'num'), _deltaTime: S('raw_dt', 'num') });
  let out = HEADER + '#![allow(clippy::all, unused_parens, unused_variables, unused_braces, unused_mut, unused_assignments, unused_imports, non_snake_case)]\n';
  out += 'use crate::arinc::Word;\nuse crate::fwc::Core;\nuse crate::js::{js_round, J};\nuse crate::vars::Vars;\n\n';
  out += 'pub fn acquire(c: &mut Core, v: &dyn Vars, dt: f64, raw_dt: f64) {\n';
  for (let i = i0; i < i1; i++) {
    const st = list[i];
    const line = core.getLineAndCharacterOfPosition(st.getStart(core)).line + 1;
    if (ts.isVariableStatement(st)) {
      try {
        const decls = [];
        let c2 = ctx;
        for (const d of st.declarationList.declarations) {
          const [code, env] = declare(d, c2);
          if (code) decls.push(code);
          c2 = c2.with(env);
        }
        for (const code of decls) out += `    ${code}\n`;
        ctx = c2;
      } catch (err) {
        if (!(err instanceof Unsupported)) throw err;
        report.hand.push(`update L${line}: ${err.message}`);
        for (const d of st.declarationList.declarations) {
          const name = `l_${snake(d.name.text)}`;
          out += `    let mut ${name} = crate::hand::u${line}_${snake(d.name.text)}(c, v, dt);\n`;
          ctx = ctx.with({ [d.name.text]: { ...S(name, 'num'), local: true } });
        }
      }
      continue;
    }
    const code = translate(`update L${line}`, st, ctx, stmt);
    out += code === null ? `    crate::hand::u${line}(c, v, dt);\n` : code === '' ? '' : `    ${code.replace(/\n/g, '\n    ')}\n`;
  }
  out += '}\n';
  updateLocals = Object.entries(ctx.env).filter(([, x]) => x.local).map(([k, x]) => [k, x.code, x.type]);
  return out;
}
