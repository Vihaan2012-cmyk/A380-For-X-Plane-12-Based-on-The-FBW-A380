class Unsupported extends Error {}

function fail(node, why) {
  throw new Unsupported(`${why}: ${node.getText().slice(0, 160)}`);
}

const S = (code, type) => ({ code, type });

function toBool(e) {
  switch (e.type) {
    case 'bool':
      return e.code;
    case 'num':
      return `(${e.code} != 0.0)`;
    case 'optnum':
      return `${e.code}.is_some_and(|x| x != 0.0)`;
    case 'str':
      return `!${e.code}.is_empty()`;
    case 'optstr':
      return `${e.code}.is_some_and(|x| !x.is_empty())`;
    case 'null':
    case 'undef':
      return 'false';
    case 'j':
      return `${e.code}.truthy()`;
    default:
      throw new Unsupported(`toBool of ${e.type}`);
  }
}

function toJ(e) {
  switch (e.type) {
    case 'bool':
      return `J::B(${e.code})`;
    case 'num':
      return `J::N(${e.code})`;
    case 'optnum':
      return `J::opt(${e.code})`;
    case 'str':
      return `J::S(${e.code})`;
    case 'optstr':
      return `J::opt_s(${e.code})`;
    case 'null':
      return 'J::Null';
    case 'undef':
      return 'J::Undef';
    case 'j':
      return e.code;
    default:
      throw new Unsupported(`toJ of ${e.type}`);
  }
}

function toNum(e) {
  if (e.type === 'num') return e.code;
  if (e.type === 'bool') return `(${e.code} as u8 as f64)`;
  if (e.type === 'j') return `${e.code}.num()`;
  throw new Unsupported(`toNum of ${e.type}`);
}

function unify(a, b) {
  if (a.type === b.type) return [a, b, a.type];
  const t = new Set([a.type, b.type]);
  if (t.has('str') && (t.has('null') || t.has('undef') || t.has('optstr'))) {
    const w = (x) => (x.type === 'str' ? S(`Some(${x.code})`, 'optstr') : x.type === 'optstr' ? x : S('None', 'optstr'));
    return [w(a), w(b), 'optstr'];
  }
  if (t.has('optstr') && (t.has('null') || t.has('undef'))) {
    const w = (x) => (x.type === 'optstr' ? x : S('None', 'optstr'));
    return [w(a), w(b), 'optstr'];
  }
  if (t.has('num') && (t.has('null') || t.has('undef') || t.has('optnum'))) {
    const w = (x) => (x.type === 'num' ? S(`Some(${x.code})`, 'optnum') : x.type === 'optnum' ? x : S('None', 'optnum'));
    return [w(a), w(b), 'optnum'];
  }
  if (t.has('optnum') && (t.has('null') || t.has('undef'))) {
    const w = (x) => (x.type === 'optnum' ? x : S('None', 'optnum'));
    return [w(a), w(b), 'optnum'];
  }
  return [S(toJ(a), 'j'), S(toJ(b), 'j'), 'j'];
}

class Ctx {
  constructor(root, env = {}) {
    this.root = root;
    this.env = env;
    this.usesV = false;
  }
  with(env) {
    const c = new Ctx(this.root, { ...this.env, ...env });
    c.parent = this;
    return c;
  }
  markV() {
    let c = this;
    while (c) {
      c.usesV = true;
      c = c.parent;
    }
  }
}

// `this.fws.NAME` (or `this.NAME` inside FwsCore-owned objects) as a value: the subject's current value.
function fwsMember(name, node, ctx) {
  if (ctx.root === 'inop' && (name === 'partSplrs' || name === 'mostSplrs')) return S(`c.${snake(name)}()`, 'bool');
  if (fields.has(name)) {
    const f = fields.get(name);
    return { ...S(`c.s.${f.rust}`, f.kind), member: name };
  }
  if (methods.has(name)) {
    const m = methods.get(name);
    if (m.alias) return fwsMember(m.alias, node, ctx);
    return { ...S(`c.${m.rust}()`, METHOD_TYPES[name] || 'bool'), member: name };
  }
  if (nodes.has(name)) return { ...S(`c.s.${nodes.get(name).rust}`, 'node'), member: name };
  if (name === 'activeAbnormalNonSensedKeys') return S('c.active_abnormal_non_sensed_keys', 'set');
  if (name === 'fws1Failed' || name === 'fws2Failed') return S(`c.${snake(name)}`, 'bool');
  if (name === 'presentedFailures' || name === 'allCurrentFailures') return S(`c.${snake(name)}`, 'idlist');
  fail(node, `unknown fws member ${name}`);
}

// A bare `this.fws.X` operand of `!`, `&&`, `||` or a condition is the Subscribable object itself (always truthy),
// not its value; only plain class fields hold values.
function operand(node, ctx) {
  const n = strip(node);
  if (ts.isPropertyAccessExpression(n)) {
    const m = memberChain(n, ctx);
    if (m && m.member && !(fields.has(m.member) && fields.get(m.member).plain)) return S('true', 'bool');
  }
  return emit(node, ctx);
}

function memberChain(e, ctx) {
  // returns the base subject for this.fws.X / this.X
  if (ts.isPropertyAccessExpression(e)) {
    const obj = strip(e.expression);
    if (ts.isPropertyAccessExpression(obj) && obj.expression.kind === ts.SyntaxKind.ThisKeyword && obj.name.text === 'fws') {
      return fwsMember(e.name.text, e, ctx);
    }
    if (obj.kind === ts.SyntaxKind.ThisKeyword) return fwsMember(e.name.text, e, ctx);
  }
  return null;
}

function emit(node, ctx) {
  const e = strip(node);
  switch (e.kind) {
    case ts.SyntaxKind.TrueKeyword:
      return S('true', 'bool');
    case ts.SyntaxKind.FalseKeyword:
      return S('false', 'bool');
    case ts.SyntaxKind.NullKeyword:
      return S('J::Null', 'null');
  }
  if (ts.isIdentifier(e)) {
    if (e.text === 'undefined') return S('J::Undef', 'undef');
    if (e.text === 'Infinity') return S('f64::INFINITY', 'num');
    if (e.text in ctx.env) return ctx.env[e.text];
    if (e.text in ENUM_VALUES) return S(f64(ENUM_VALUES[e.text]), 'num');
    fail(e, 'unknown identifier');
  }
  if (ts.isNumericLiteral(e)) return S(f64(Number(e.text.replace(/_/g, ''))), 'num');
  if (ts.isStringLiteral(e) || ts.isNoSubstitutionTemplateLiteral(e)) return S(JSON.stringify(e.text), 'str');
  if (ts.isPrefixUnaryExpression(e)) {
    const o = e.operator === ts.SyntaxKind.ExclamationToken ? operand(e.operand, ctx) : emit(e.operand, ctx);
    if (e.operator === ts.SyntaxKind.ExclamationToken) return S(`!${wrap(toBool(o))}`, 'bool');
    if (e.operator === ts.SyntaxKind.MinusToken) return S(`-${wrap(toNum(o))}`, 'num');
    fail(e, 'prefix');
  }
  if (ts.isConditionalExpression(e)) {
    const c = toBool(operand(e.condition, ctx));
    const [a, b, t] = unify(emit(e.whenTrue, ctx), emit(e.whenFalse, ctx));
    return S(`(if ${c} { ${a.code} } else { ${b.code} })`, t);
  }
  if (ts.isBinaryExpression(e)) return binary(e, ctx);
  if (ts.isArrayLiteralExpression(e)) {
    if (e.elements.some(ts.isSpreadElement)) {
      const parts = e.elements.map((x) => {
        if (!ts.isSpreadElement(x)) return `a.push(${toJ(emit(x, ctx))});`;
        const inner = strip(x.expression);
        if (ts.isConditionalExpression(inner)) {
          const c = toBool(emit(inner.condition, ctx));
          const sp = (n) => {
            const r = emit(n, ctx);
            if (r.type === 'jarr') return `a.extend(${r.code});`;
            if (r.type === 'str' && r.code === '""') return '';
            fail(n, 'spread');
          };
          return `if ${c} { ${sp(inner.whenTrue)} } else { ${sp(inner.whenFalse)} }`;
        }
        const r = emit(inner, ctx);
        if (r.type === 'jarr') return `a.extend(${r.code});`;
        fail(x, 'spread');
      });
      return S(`{ let mut a: Vec<J> = Vec::new(); ${parts.join(' ')} a }`, 'jarr');
    }
    const items = e.elements.map((x) => operand(x, ctx));
    return S(`vec![${items.map(toJ).join(', ')}]`, 'jarr');
  }
  if (ts.isElementAccessExpression(e)) {
    const obj = emit(e.expression, ctx);
    const idx = emit(e.argumentExpression, ctx);
    if (obj.type === 'checked') return S(`checked.get(${toNum(idx)} as usize).copied().unwrap_or(J::Undef)`, 'j');
    fail(e, 'element access');
  }
  if (ts.isPropertyAccessExpression(e)) {
    const m = memberChain(e, ctx);
    if (m) return m;
    if (e.getText() in ENUM_VALUES) return S(f64(ENUM_VALUES[e.getText()]), 'num');
    const obj = emit(e.expression, ctx);
    const name = e.name.text;
    if (obj.type === 'node' && name === 'previousInput') return S(`${obj.code}.previous_input()`, 'bool');
    if (obj.type === 'word' && name === 'value') return S(`${obj.code}.value()`, 'num');
    if (obj.type === 'jarr' && name === 'length') return S(`(${obj.code}.len() as f64)`, 'num');
    if (e.getText() === 'Number.MAX_SAFE_INTEGER') return S('9007199254740991.0', 'num');
    fail(e, 'property access');
  }
  if (ts.isCallExpression(e)) return call(e, ctx);
  if (ts.isNewExpression(e) && e.expression.getText() === 'Arinc429Word') return S(`Word::from_simvar(${toNum(emit(e.arguments[0], ctx))})`, 'word');
  fail(e, `syntax ${ts.SyntaxKind[e.kind]}`);
}

function templ(t, ctx) {
  let fmt = t.head.text.replace(/[{}]/g, (m) => m + m);
  const args = [];
  for (const sp of t.templateSpans) {
    const r = emit(sp.expression, ctx);
    args.push(r.type === 'optnum' ? `${r.code}.unwrap_or(0.0)` : toNum(r));
    fmt += '{}' + sp.literal.text.replace(/[{}]/g, (m) => m + m);
  }
  return `format!(${JSON.stringify(fmt)}, ${args.join(', ')})`;
}

function wrap(code) {
  return /^[\w.:]+(\(\))?$/.test(code) ? code : `(${code})`;
}

function binary(e, ctx) {
  const op = e.operatorToken.kind;
  const K = ts.SyntaxKind;
  if (op === K.AmpersandAmpersandToken || op === K.BarBarToken) {
    const a = operand(e.left, ctx);
    const b = operand(e.right, ctx);
    const rop = op === K.AmpersandAmpersandToken ? '&&' : '||';
    if (a.type === 'bool' && b.type === 'bool') return S(`(${a.code} ${rop} ${b.code})`, 'bool');
    if (a.type === 'num' && b.type === 'num') {
      return op === K.AmpersandAmpersandToken
        ? S(`{ let a = ${a.code}; if a != 0.0 { ${b.code} } else { a } }`, 'num')
        : S(`{ let a = ${a.code}; if a != 0.0 { a } else { ${b.code} } }`, 'num');
    }
    const ja = toJ(a);
    const jb = toJ(b);
    return op === K.AmpersandAmpersandToken
      ? S(`{ let a = ${ja}; if a.truthy() { ${jb} } else { a } }`, 'j')
      : S(`{ let a = ${ja}; if a.truthy() { a } else { ${jb} } }`, 'j');
  }
  if (op === K.QuestionQuestionToken) {
    const a = emit(e.left, ctx);
    const b = emit(e.right, ctx);
    if (a.type === 'optnum' && b.type === 'num') return S(`${a.code}.unwrap_or(${b.code})`, 'num');
    if (a.type === 'num') return a;
    fail(e, '??');
  }
  const a = emit(e.left, ctx);
  const b = emit(e.right, ctx);
  const cmp = {
    [K.EqualsEqualsEqualsToken]: '==',
    [K.EqualsEqualsToken]: '==',
    [K.ExclamationEqualsEqualsToken]: '!=',
    [K.ExclamationEqualsToken]: '!=',
    [K.LessThanToken]: '<',
    [K.GreaterThanToken]: '>',
    [K.LessThanEqualsToken]: '<=',
    [K.GreaterThanEqualsToken]: '>=',
  }[op];
  if (cmp) {
    if (cmp === '==' || cmp === '!=') {
      if (a.type === 'bool' && b.type === 'num') {
        if (b.code === '1.0') return S(cmp === '==' ? a.code : `!${wrap(a.code)}`, 'bool');
        if (b.code === '0.0') return S(cmp === '==' ? `!${wrap(a.code)}` : a.code, 'bool');
        return S(cmp === '==' ? 'false' : 'true', 'bool');
      }
      if (a.type === 'bool' && b.type === 'bool') return S(`(${a.code} ${cmp} ${b.code})`, 'bool');
      if (a.type === 'str' && b.type === 'str') return S(`(${a.code} ${cmp} ${b.code})`, 'bool');
      if (a.type === 'optnum' && (b.type === 'null' || b.type === 'undef')) return S(cmp === '==' ? `${a.code}.is_none()` : `${a.code}.is_some()`, 'bool');
      if (a.type === 'num' && b.type === 'num') return S(`(${a.code} ${cmp} ${b.code})`, 'bool');
      if (a.type === 'num' && b.type === 'bool') return S(`(${a.code} ${cmp} (${b.code} as u8 as f64))`, 'bool');
      fail(e, `compare ${a.type} ${b.type}`);
    }
    return S(`(${toNum(a)} ${cmp} ${toNum(b)})`, 'bool');
  }
  const arith = { [K.PlusToken]: '+', [K.MinusToken]: '-', [K.AsteriskToken]: '*', [K.SlashToken]: '/' }[op];
  if (arith) return S(`(${toNum(a)} ${arith} ${toNum(b)})`, 'num');
  fail(e, 'binary op');
}

const MAP_FNS = {
  'SubscribableMapFunctions.and()': (args) => S(args.length ? `(${args.map(toBool).join(' && ')})` : 'true', 'bool'),
  'SubscribableMapFunctions.or()': (args) => S(args.length ? `(${args.map(toBool).join(' || ')})` : 'false', 'bool'),
  'SubscribableMapFunctions.nor()': (args) => S(args.length ? `!(${args.map(toBool).join(' || ')})` : 'true', 'bool'),
  'SubscribableMapFunctions.nand()': (args) => S(args.length ? `!(${args.map(toBool).join(' && ')})` : 'false', 'bool'),
  'SubscribableMapFunctions.not()': (args) => S(`!${wrap(toBool(args[0]))}`, 'bool'),
};

function applyFn(fn, values, ctx) {
  fn = strip(fn);
  const key = fn.getText();
  if (MAP_FNS[key]) return MAP_FNS[key](values);
  if (!ts.isArrowFunction(fn)) fail(fn, 'map function');
  const env = {};
  if (fn.parameters.length === 1 && ts.isArrayBindingPattern(fn.parameters[0].name)) {
    fn.parameters[0].name.elements.forEach((el, i) => {
      if (ts.isBindingElement(el)) env[el.name.text] = values[i];
    });
  } else if (fn.parameters.length === 1 && ts.isIdentifier(fn.parameters[0].name)) {
    if (values.length !== 1) fail(fn, 'rest parameter map');
    env[fn.parameters[0].name.text] = values[0];
  } else fail(fn, 'map parameters');
  return emitBody(fn.body, ctx.with(env));
}

let tmpCounter = 0;
function emitBody(body, ctx) {
  body = strip(body);
  if (ts.isBlock(body)) {
    const lets = [];
    let c = ctx;
    for (const st of body.statements) {
      if (ts.isVariableStatement(st)) {
        for (const d of st.declarationList.declarations) {
          const r = emit(d.initializer, c);
          const tmp = `t${tmpCounter++}`;
          lets.push(`let ${tmp} = ${r.code};`);
          c = c.with({ [d.name.text]: S(tmp, r.type) });
        }
      } else if (ts.isReturnStatement(st)) {
        const r = emit(st.expression, c);
        return S(`{ ${lets.join(' ')} ${r.code} }`, r.type);
      } else fail(st, 'statement');
    }
    fail(body, 'block without return');
  }
  return emit(body, ctx);
}

function call(e, ctx) {
  const callee = strip(e.expression);
  const text = callee.getText();
  if (text === 'SimVar.GetSimVarValue') {
    const n = strip(e.arguments[0]);
    if (!ts.isStringLiteral(n)) fail(e, 'dynamic simvar');
    ctx.markV();
    return S(`v.get(${JSON.stringify(n.text)})`, 'num');
  }
  if (text === 'MappedSubject.create') {
    const values = e.arguments.slice(1).map((a) => emit(a, ctx));
    return applyFn(e.arguments[0], values, ctx);
  }
  if (text === 'Subject.create') {
    const a = strip(e.arguments[0]);
    const t = a.getText();
    const aural = /^FwcAuralWarning\.(\w+)$/.exec(t);
    if (aural) return S(`Aural::${aural[1]}`, 'aural');
    return emit(a, ctx);
  }
  if (text === 'xor') return S(`(${toBool(emit(e.arguments[0], ctx))} != ${toBool(emit(e.arguments[1], ctx))})`, 'bool');
  if (text === 'countTrue') return S(`(${e.arguments.map((a) => `(${toBool(emit(a, ctx))} as u8 as f64)`).join(' + ')})`, 'num');
  if (ts.isIdentifier(callee) && ctx.env[text] && ctx.env[text].type === 'arrow') {
    const fn = ctx.env[text].fn;
    const env = {};
    fn.parameters.forEach((p, i) => (env[p.name.text] = emit(e.arguments[i], ctx)));
    return emitBody(fn.body, ctx.with(env));
  }
  if (text === 'SimVar.GetSimVarValue' && ts.isTemplateExpression(strip(e.arguments[0]))) {
    ctx.markV();
    return S(`v.get(&${templ(strip(e.arguments[0]), ctx)})`, 'num');
  }
  if (/^Math\.(abs|round|min|max|ceil|floor)$/.test(text)) {
    const fnName = text.slice(5);
    const args = e.arguments.map((a) => toNum(emit(a, ctx)));
    if (fnName === 'min' || fnName === 'max') return S(args.slice(1).reduce((acc, x) => `${acc}.${fnName}(${x})`, args[0]), 'num');
    if (fnName === 'round') return S(`js_round(${args[0]})`, 'num');
    return S(`${wrap(args[0])}.${fnName}()`, 'num');
  }
  if (ts.isPropertyAccessExpression(callee)) {
    const method = callee.name.text;
    const objNode = strip(callee.expression);
    if (method === 'filter' && e.arguments.length === 1 && strip(e.arguments[0]).getText() === 'Boolean') {
      const arr = emit(objNode, ctx);
      if (arr.type !== 'jarr') fail(e, 'filter');
      return S(`${arr.code}.into_iter().filter(|x| x.truthy()).collect::<Vec<J>>()`, 'jarr');
    }
    if ((method === 'adirsMessage1' || method === 'adirsMessage2') && strip(objNode).getText() === 'this.fws') {
      const a = e.arguments.map((x) => emit(x, ctx));
      return S(`c.${snake(method)}(${toNum(a[0])}, ${toBool(a[1])})`, 'num');
    }
    if (method === 'map') {
      const base = emit(objNode, ctx);
      if (base.type === 'set') return applySetMap(e.arguments[0], base, ctx);
      return applyFn(e.arguments[0], [base], ctx);
    }
    if (strip(objNode).getText() === 'this.failuresConsumer' && method === 'isActive') {
      return S(`c.failure_active(${JSON.stringify(e.arguments[0].getText().replace(/^A380Failure\./, ''))})`, 'bool');
    }
    if (strip(objNode).getText() === 'Arinc429Word' && method === 'fromSimVarValue') {
      const n = strip(e.arguments[0]);
      if (ts.isStringLiteral(n)) {
        ctx.markV();
        return S(`Word::from_simvar(v.get(${JSON.stringify(n.text)}))`, 'word');
      }
    }
    if (strip(objNode).getText() === 'PitchTrimUtils') {
      const a = e.arguments.map((x) => toNum(emit(x, ctx)));
      return S(`crate::fwc::pitch_trim_${snake(method).replace('pitch_trim_', '')}(${a.join(', ')})`, 'bool');
    }
    if (method === 'filter' && e.arguments.length === 1 && ts.isArrowFunction(strip(e.arguments[0]))) {
      const arr = emit(objNode, ctx);
      if (arr.type !== 'jarr') fail(e, 'filter');
      const fn = strip(e.arguments[0]);
      const p = fn.parameters[0].name.text;
      const body = toBool(emitBody(fn.body, ctx.with({ [p]: S('(*x)', 'j') })));
      return S(`${arr.code}.into_iter().filter(|x| ${body}).collect::<Vec<J>>()`, 'jarr');
    }
    const obj = emit(objNode, ctx);
    if (method === 'get' && e.arguments.length === 0) {
      if (['bool', 'num', 'optnum', 'word', 'str', 'j'].includes(obj.type)) return obj;
      fail(e, `get on ${obj.type}`);
    }
    if (method === 'read' && obj.type === 'node') return S(`${obj.code}.read()`, nodes.get(obj.member).ty === 'Clock' ? 'num' : 'bool');
    if (method === 'write' && obj.type === 'node') {
      const ty = nodes.get(obj.member).ty;
      const a = e.arguments.map((x) => emit(x, ctx));
      if (ty === 'Confirm' || ty === 'Monostable') return S(`{ let a0 = ${toBool(a[0])}; let a1 = ${toNum(a[1])}; ${obj.code}.write(a0, a1, c.skip) }`, 'bool');
      if (ty === 'Memory') return S(`{ let a0 = ${toBool(a[0])}; let a1 = ${toBool(a[1])}; ${obj.code}.write(a0, a1) }`, 'bool');
      if (ty === 'Pulse') return S(`{ let a0 = ${toBool(a[0])}; ${obj.code}.write(a0) }`, 'bool');
      if (ty === 'Clock') return S(`{ let a0 = ${toBool(a[0])}; let a1 = ${toNum(a[1])}; ${obj.code}.write(a0, a1) }`, 'num');
    }
    if (obj.type === 'word') {
      const args = e.arguments.map((a) => emit(a, ctx));
      switch (method) {
        case 'valueOr':
          return S(`${obj.code}.value_or(${toNum(args[0])})`, 'num');
        case 'bitValueOr':
          return S(`${obj.code}.bit_value_or(${toNum(args[0])} as u32, ${toBool(args[1])})`, 'bool');
        case 'bitValue':
          return S(`${obj.code}.bit_value(${toNum(args[0])} as u32)`, 'bool');
        case 'isNormalOperation':
          return S(`${obj.code}.is_normal()`, 'bool');
        case 'isFailureWarning':
          return S(`${obj.code}.is_failure_warning()`, 'bool');
        case 'isNoComputedData':
          return S(`${obj.code}.is_no_computed_data()`, 'bool');
        case 'isFunctionalTest':
          return S(`${obj.code}.is_functional_test()`, 'bool');
        case 'isInvalid':
          return S(`${obj.code}.is_invalid()`, 'bool');
      }
    }
    if (obj.type === 'set' && method === 'has') return S(`${obj.code}.contains(&(${toNum(emit(e.arguments[0], ctx))} as u32))`, 'bool');
  }
  fail(e, 'call');
}

function applySetMap(fn, base, ctx) {
  fn = strip(fn);
  const body = strip(fn.body);
  const p = fn.parameters[0].name.text;
  if (ts.isCallExpression(body) && strip(body.expression).getText() === `${p}.has`) {
    return S(`${base.code}.contains(&(${toNum(emit(body.arguments[0], ctx))} as u32))`, 'bool');
  }
  fail(fn, 'set map');
}

// ---------------------------------------------------------------- tables

function objectProp(obj, name) {
  return obj.properties.find((p) => ts.isPropertyAssignment(p) && propName(p) === name);
}

function tableEntries(sf, className, member) {
  const cls = classOf(sf, className);
  const prop = cls.members.find((m) => ts.isPropertyDeclaration(m) && propName(m) === member);
  if (!prop) throw new Error(`${className}.${member} not found`);
  const obj = strip(prop.initializer);
  const entries = obj.properties.filter(ts.isPropertyAssignment).map((p) => ({ key: propName(p), raw: p.name.getText(sf), obj: strip(p.initializer) }));
  return jsOrder(entries);
}

function isIndexKey(k) {
  return /^(0|[1-9]\d*)$/.test(k) && Number(k) < 4294967295;
}

function jsOrder(entries) {
  const ints = entries.filter((e) => isIndexKey(e.key)).sort((a, b) => Number(a.key) - Number(b.key));
  const rest = entries.filter((e) => !isIndexKey(e.key));
  return [...ints, ...rest];
}

const report = { hand: [], notes: [] };

function translate(label, node, ctx, fn) {
  try {
    return fn(node, ctx);
  } catch (err) {
    if (err instanceof Unsupported) {
      report.hand.push(`${label}: ${err.message}`);
      return null;
    }
    throw err;
  }
}

function boolExpr(node, ctx) {
  return toBool(emit(node, ctx));
}

function arrayFn(node, ctx) {
  const f = strip(node);
  if (!ts.isArrowFunction(f)) fail(f, 'not an arrow');
  let c = ctx;
  if (f.parameters.length === 1) c = ctx.with({ [f.parameters[0].name.text]: S('checked', 'checked') });
  const r = emitBody(f.body, c);
  if (r.type !== 'jarr') fail(f, `array function returns ${r.type}`);
  return r.code;
}

function auralExpr(node, ctx) {
  const r = emit(node, ctx);
  if (r.type === 'aural') return r.code;
  fail(node, 'aural');
}

function auralMap(node, ctx) {
  const e = strip(node);
  if (ts.isCallExpression(e) && ts.isPropertyAccessExpression(e.expression) && e.expression.name.text === 'map') {
    const base = emit(e.expression.expression, ctx);
    const fn = strip(e.arguments[0]);
    const p = fn.parameters[0].name.text;
    const body = strip(fn.body);
    if (ts.isConditionalExpression(body) && strip(body.condition).getText() === p) {
      const a = /FwcAuralWarning\.(\w+)/.exec(body.whenTrue.getText())[1];
      const b = /FwcAuralWarning\.(\w+)/.exec(body.whenFalse.getText())[1];
      return `if ${toBool(base)} { Aural::${a} } else { Aural::${b} }`;
    }
  }
  return auralExpr(node, ctx);
}

