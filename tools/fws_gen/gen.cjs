function topicOf(e) {
  const c = strip(e);
  const arg = c.arguments[0];
  return arg.getText(core).replace(/^[`'"]|[`'"]$/g, '');
}

function f64(v) {
  if (v === undefined) return '0.0';
  const s = String(v);
  return /[.e]/.test(s) ? s : s + '.0';
}

