function parse(file) {
  const text = fs.readFileSync(path.join(DIR, file), 'utf8');
  return ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
}

function snake(n) {
  return n
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .toLowerCase();
}

function classOf(sf, name) {
  let found = null;
  ts.forEachChild(sf, (n) => {
    if (ts.isClassDeclaration(n) && n.name && n.name.text === name) found = n;
  });
  if (!found) throw new Error(`class ${name} not found`);
  return found;
}

function propName(p) {
  const n = p.name;
  if (ts.isIdentifier(n) || ts.isStringLiteral(n) || ts.isNumericLiteral(n)) return n.text;
  return null;
}

function strip(e) {
  while (e && (ts.isParenthesizedExpression(e) || ts.isAsExpression(e) || ts.isNonNullExpression(e))) e = e.expression;
  return e;
}

