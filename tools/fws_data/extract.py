def s(text):
    out = ['"']
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 32 or ord(ch) == 127:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def opt(value, fmt=lambda v: v):
    return "None" if value is None else "Some(%s)" % fmt(value)


def strs(values):
    return "&[%s]" % ", ".join(s(v) for v in values)


def ids(values):
    return "&[%s]" % ", ".join(str(int(v)) for v in values)


def run_entry():
    esbuild = FBW / "node_modules" / ".bin" / ("esbuild.cmd" if sys.platform == "win32" else "esbuild")
    with tempfile.TemporaryDirectory() as tmp:
        bundle = Path(tmp) / "fws_data.cjs"
        subprocess.run([str(esbuild), str(HERE / "entry.ts"), "--bundle", "--platform=node", "--format=cjs",
                        "--log-level=warning", f"--outfile={bundle}"], check=True)
        proc = subprocess.run(["node", str(bundle)], check=True, capture_output=True, text=True, encoding="utf-8")
    return json.loads(proc.stdout)


def run_meta():
    proc = subprocess.run(["node", str(HERE / "fws_meta.cjs"), str(FBW)], check=True, capture_output=True, text=True, encoding="utf-8")
    return json.loads(proc.stdout)


def item_rust(it):
    extra = set(it) - ITEM_KEYS
    assert not extra, (it, extra)
    if it.get("condition"):
        kind = "Condition"
    elif "labelNotCompleted" in it:
        kind = "Action"
    else:
        kind = "Plain"
    style = it.get("style", "Standard")
    assert style in STYLES, style
    return (
        "Item { name: %s, kind: ItemKind::%s, sensed: %s, level: %d, style: Style::%s, label: %s, label_completed: %s, "
        "colon_if_completed: %s, time: %s, append_time_if_elapsed: %s }"
        % (
            s(it["name"]), kind, str(bool(it["sensed"])).lower(), int(it.get("level", 0)), style,
            s(it.get("labelNotCompleted", "")), opt(it.get("labelCompleted"), s),
            str(bool(it.get("colonIfCompleted", True))).lower(), opt(it.get("time")),
            str(bool(it.get("appendTimeIfElapsed", False))).lower(),
        )
    )


def title_parts(title):
    colour = "None"
    m = re.match(r"\x1b<(\d)m", title)
    if m:
        colour = COLOUR[m.group(1)]
    sysm = SYSTEM.search(title)
    system = ESC.sub("", sysm.group(1)).strip() if sysm else ""
    plain = re.sub(r"[ \t]+", " ", ESC.sub("", title)).strip()
    return colour, system, plain


def items_rust(items):
    return "&[%s]" % ", ".join(item_rust(i) for i in items)


def shape_rust(shape):
    if shape is None:
        return "ItemsFn::Absent"
    if shape["kind"] != "array":
        return "ItemsFn::Dynamic"
    lit = shape.get("literal")
    return "ItemsFn::Array { len: %s, literal: %s }" % (
        opt(shape["len"]),
        "None" if lit is None else "Some(&[%s])" % ", ".join(str(b).lower() for b in lit),
    )


def aural_rust(a):
    if a is None:
        return "Aural::Default"
    src = a["src"]
    m = CONST_AURAL.match(src)
    if m:
        return "Aural::Constant(AuralKind::%s)" % m.group(1)
    m = AURAL.match(src)
    if m:
        return "Aural::Signal { name: %s, on: AuralKind::%s, off: AuralKind::%s }" % (s(m.group(1)), m.group(2), m.group(3))
    return "Aural::Expr { refs: %s, src: %s }" % (strs(a["refs"]), s(src))


def idlist_rust(v):
    if v is None:
        return "IdList::NONE"
    return "IdList { ids: %s, conditional: %s }" % (ids(v["ids"]), str(v["conditional"]).lower())


def alert_rust(e, source):
    phases = e.get("phases") or []
    f = e.get("failure", 0)
    page = e.get("sysPage", "None")
    act = e["active"]
    lines = [
        "Alert { id: %s, comment: %s, source: AlertSource::%s, phases_inhibited: Phases::from_list(&[%s]), level: Level::from_failure(%d), sd_page: SdPage::%s,"
        % (e["id"], s(e["comment"]), source, ", ".join(str(p) for p in phases), f, page),
        "  aural: %s, active_expr: %s, active_refs: %s, active_vars: %s, suppressed_by: %s,"
        % (aural_rust(e.get("aural")), s(act["src"]), strs(act["refs"]), strs(act["vars"]), ids(e.get("suppressedBy", []))),
        "  monitor_confirm_time: %s, cancel: %s, non_procedure_key: %s,"
        % (opt(e.get("monitorConfirmTime"), lambda v: "%r" % float(v)), str(e.get("cancel", True)).lower(), str(e.get("nonProcedureKey", False)).lower()),
        "  items_to_show: %s, items_checked: %s, items_active: %s, items_timer: %s,"
        % (shape_rust(e.get("show")), shape_rust(e.get("checked")), shape_rust(e.get("active_items")), shape_rust(e.get("timer"))),
        "  %s }" % ", ".join("%s: %s" % (rn, idlist_rust(e.get(jn))) for jn, rn in LISTS),
    ]
    return "\n    ".join(lines)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    data = run_entry()
    meta = run_meta()
    non_sensed = {str(n["id"]): n["category"] for n in data["nonSensed"]}
    fms = data["fmsPredUnreliable"]
    spread_uses = sum((ABN / (g + ".ts")).read_text(encoding="utf-8-sig").count("...FMS_PRED_UNRELIABLE_CHECKLIST_ITEM") for g, _ in GROUPS)
    patched = 0
    for g in data["groups"].values():
        for table in g.values():
            for proc in table.values():
                for n, it in enumerate(proc["items"]):
                    if "name" not in it:
                        proc["items"][n] = {**fms, **it}
                        patched += 1
    assert patched == spread_uses, (patched, spread_uses)

    procedures, deferred, expected = [], [], []
    for gkey, gname in GROUPS:
        g = data["groups"][gkey]
        text = (ABN / (gkey + ".ts")).read_text(encoding="utf-8-sig")
        marks = list(ENTRY.finditer(text))
        split = text.find("EcamDeferredProcAta")
        raw_sensed = sum(1 for m in marks if split < 0 or m.start() < split)
        raw_deferred = len(marks) - raw_sensed
        assert raw_sensed == len(g["sensed"]), (gkey, raw_sensed, len(g["sensed"]))
        assert raw_deferred == len(g.get("deferred", {})), (gkey, raw_deferred)
        expected.append((gname, raw_sensed, raw_deferred))
        for pid, p in g["sensed"].items():
            colour, system, plain = title_parts(p["title"])
            kind = "Secondary" if gkey == "secondary-failures" else "NonSensed" if pid in non_sensed else "Sensed"
            procedures.append((int(pid), "AtaFile::%s" % gname, p, colour, system, plain, kind))
        for pid, p in g.get("deferred", {}).items():
            deferred.append((int(pid), gname, p))
    procedures.sort(key=lambda r: r[0])
    deferred.sort(key=lambda r: r[0])
    assert len({p[0] for p in procedures}) == len(procedures)
    assert sorted(int(i) for i in data["merged"]["sensedIds"]) == [p[0] for p in procedures]
    assert sorted(int(i) for i in data["merged"]["deferredIds"]) == [d[0] for d in deferred]
    missing = [i for i in non_sensed if int(i) not in {p[0] for p in procedures}]
    assert not missing, missing

    body = [HEADER, "use crate::types::*;\n\n", "pub static PROCEDURES: &[Procedure] = &[\n"]
    for pid, ata, p, colour, system, plain, kind in procedures:
        rec = p.get("recommendation")
        recs = "None" if rec is None else "Some(Recommendation::%s)" % ("LandAsap" if rec == "LAND ASAP" else "LandAnsa")
        body.append(
            "  Procedure { id: %d, ata: %s, kind: Kind::%s, sensed: %s, title: %s, plain_title: %s, system: %s, colour: Colour::%s, recommendation: %s, items: %s },\n"
            % (pid, ata, kind, str(bool(p["sensed"])).lower(), s(p["title"]), s(plain), s(system), colour, recs, items_rust(p["items"]))
        )
    body.append("];\n")
    (OUT / "procedures.rs").write_text("".join(body), encoding="utf-8", newline="\n")

    types = {"ALL_PHASES": "AllPhases", "AT_TOP_OF_DESCENT": "AtTopOfDescent", "FOR_APPROACH": "ForApproach", "FOR_LANDING": "ForLanding"}
    order = [types[k] for k, v in sorted(data["deferredTypes"].items(), key=lambda kv: kv[1])]
    body = [HEADER, "use crate::types::*;\n\n", "pub static DEFERRED: &[Deferred] = &[\n"]
    for pid, gname, p in deferred:
        body.append(
            "  Deferred { id: %d, ata: AtaFile::%s, from_abnormal: %s, title: %s, kind: DeferredType::%s, items: %s },\n"
            % (pid, gname, ids(p["fromAbnormalProcs"]), opt(p.get("title"), s), order[p["type"]], items_rust(p["items"]))
        )
    body.append("];\n")
    (OUT / "deferred.rs").write_text("".join(body), encoding="utf-8", newline="\n")

    alerts = []
    for key, source in FWS_SOURCES.items():
        for e in meta[key]:
            assert e["id"] is not None, e
            assert "unknown" not in e, e
            alerts.append((int(e["id"]), source, e))
    alerts.sort(key=lambda r: r[0])
    assert len({a[0] for a in alerts}) == len(alerts)
    body = [HEADER, "use crate::types::*;\n\n", "pub static ALERTS: &[Alert] = &[\n"]
    for aid, source, e in alerts:
        body.append("  %s,\n" % alert_rust(e, source))
    body.append("];\n")
    (OUT / "alerts.rs").write_text("".join(body), encoding="utf-8", newline="\n")

    cat = {None: "None", "ENG": "Eng", "F/CTL": "FCtl", "L/G": "LG", "NAV": "Nav", "FUEL": "Fuel", "MISCELLANEOUS": "Miscellaneous"}
    body = [HEADER, "use crate::types::*;\n\n", "pub static NON_SENSED: &[NonSensed] = &[\n"]
    for n in data["nonSensed"]:
        body.append("  NonSensed { id: %d, category: Category::%s },\n" % (n["id"], cat[n["category"]]))
    body.append("];\n\n")
    body.append("pub static SUB_MENU: &[Category] = &[%s];\n" % ", ".join("Category::%s" % cat[c] for c in data["subMenu"]))
    (OUT / "non_sensed.rs").write_text("".join(body), encoding="utf-8", newline="\n")

    body = [HEADER, "use crate::types::*;\n\n", "pub static EXPECTED_COUNTS: &[ExpectedCount] = &[\n"]
    for gname, a, d in expected:
        body.append("  ExpectedCount { ata: AtaFile::%s, procedures: %d, deferred: %d },\n" % (gname, a, d))
    body.append("];\n\n")
    body.append("pub const MERGED_PROCEDURES: usize = %d;\npub const MERGED_DEFERRED: usize = %d;\n" % (len(data["merged"]["sensedIds"]), len(data["merged"]["deferredIds"])))
    body.append("pub const FWS_ALERTS: usize = %d;\n" % len(alerts))
    (OUT / "expected.rs").write_text("".join(body), encoding="utf-8", newline="\n")

    (OUT / "mod.rs").write_text(
        HEADER + "mod alerts;\nmod deferred;\nmod expected;\nmod non_sensed;\nmod procedures;\n\n"
        "pub use alerts::ALERTS;\npub use deferred::DEFERRED;\npub use expected::*;\npub use non_sensed::{NON_SENSED, SUB_MENU};\npub use procedures::PROCEDURES;\n",
        encoding="utf-8", newline="\n",
    )
    print(len(procedures), "procedures,", len(deferred), "deferred,", len(alerts), "alerts,", len(data["nonSensed"]), "non-sensed")


if __name__ == "__main__":
    main()
