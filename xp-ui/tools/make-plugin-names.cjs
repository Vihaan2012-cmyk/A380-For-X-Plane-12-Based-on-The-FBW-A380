'use strict';
// node make-plugin-names.cjs <api-map.json> <out xp_names.txt>
// The plugin's table from this library's variable and wire names to the names it keeps internally.

const fs = require('fs');

const map = JSON.parse(fs.readFileSync(process.argv[2] || 'E:/fbw-int/xplane-js-private/api-map.json', 'utf8'));
const out = process.argv[3] || 'E:/fbw-int/plugin/src/xp_names.txt';

const ENV = new Set(['SIMULATION TIME', 'ABSOLUTE TIME', 'SIMULATION RATE', 'ZULU DAY OF MONTH', 'ZULU MONTH OF YEAR', 'ZULU YEAR', 'ZULU TIME', 'LOCAL TIME', 'TIME OF DAY', 'ZULU SUNRISE TIME', 'ZULU SUNSET TIME', 'IS AIRCRAFT']);
const GAME = new Set(['FLIGHT NAVDATA DATE RANGE', 'FROM MACH TO KIAS', 'FROM KIAS TO MACH']);

const exact = new Map();
const prefix = new Map();
const add = (m, a, b) => {
  if (m.has(a) && m.get(a) !== b) throw new Error(`two internal names for ${a}`);
  m.set(a, b);
};
const internal = (old) => {
  const bare = old.replace(/^(A|E):/, '');
  const base = bare.replace(/:(\d+|#index#)?$/, '');
  if (ENV.has(base) && !old.startsWith('E:')) return 'E:' + bare;
  if (GAME.has(base)) return 'GAME:' + bare;
  return old;
};
for (const s of map.strings) {
  if (s.piece === 'full') {
    if (s.old.includes('#index#')) add(prefix, s.new.split('#index#')[0], internal(s.old).split('#index#')[0]);
    else add(exact, s.new, internal(s.old));
    if (/^(A:)?[A-Z ]+:$/.test(s.old)) add(prefix, s.new, internal(s.old));
  } else if (s.piece === 'head') {
    add(prefix, s.new, internal(s.old));
  }
}
for (let n = 1; n <= 4; n++) {
  for (const [suffix, field] of [['LAT', 'lat'], ['LON', 'lon'], ['ALT', 'alt']]) add(exact, `fbw/NAV_VOR_LATLONALT_${n}_${suffix}`, `fbw/radio/nav${n}/${field}`);
}
for (const n of ['INDICATED_ALTITUDE', 'PLANE_ALT_ABOVE_GROUND_MINUS_CG', 'GPS_GROUND_SPEED', 'VERTICAL_SPEED', 'SIM_ON_GROUND', 'KOHLSMAN_SETTING_HG_1', 'KOHLSMAN_SETTING_STD_1', 'AUTOPILOT_AIRSPEED_HOLD_VAR', 'AUTOPILOT_SPEED_SLOT_INDEX', 'AUTOPILOT_MACH_HOLD_VAR', 'AUTOPILOT_MANAGED_SPEED_IN_MACH', 'AUTOPILOT_HEADING_LOCK_DIR', 'AUTOPILOT_ALTITUDE_LOCK_VAR_3', 'AUTOPILOT_ALTITUDE_SLOT_INDEX']) {
  const key = `fbw/${n}`;
  if (!exact.has(key)) add(exact, key, n.replace(/_(\d+)$/, ':$1').replace(/_/g, ' '));
}
const OWN_PAGES = { 'fbw/GPS_POSITION_LAT': 'GPS POSITION LAT', 'fbw/GPS_POSITION_LON': 'GPS POSITION LON', 'fbw/PLANE_ALT_ABOVE_GROUND_MINUS_CG': 'PLANE ALT ABOVE GROUND MINUS CG', 'fbw/GPS_GROUND_SPEED': 'GPS GROUND SPEED', 'fbw/INDICATED_ALTITUDE': 'INDICATED ALTITUDE', 'sim/flightmodel/position/psi': 'PLANE HEADING DEGREES TRUE', 'sim/weather/aircraft/temperature_ambient_deg_c': 'AMBIENT TEMPERATURE', 'fbw/CABIN_SEATBELTS_ALERT_SWITCH_1': 'CABIN SEATBELTS ALERT SWITCH:1', 'sim/cockpit2/controls/gear_handle_down': 'GEAR HANDLE POSITION', 'sim/flightmodel/position/indicated_airspeed': 'AIRSPEED INDICATED', 'fbw/GLASSCOCKPIT_AUTOMATIC_BRIGHTNESS': 'GLASSCOCKPIT AUTOMATIC BRIGHTNESS', 'fbw/MAGVAR': 'MAGVAR' };
for (const [a, b] of Object.entries(OWN_PAGES)) if (!exact.has(a)) add(exact, a, b);
for (const axis of ['X', 'Y', 'Z']) add(exact, `fbw/CAMERA_POS_IN_PLANE_${axis}`, `GAME:CAMERA POS IN PLANE:${axis}`);

const lines = ['# generated by clean-avionics/tools/make-plugin-names.cjs; do not edit'];
for (const [a, b] of [...exact].sort()) lines.push(`=${a}\t${b}`);
for (const [a, b] of [...prefix].sort()) lines.push(`>${a}\t${b}`);
for (const w of map.wire) lines.push(`@${w.new}\t${w.old}`);
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log(`${exact.size} names, ${prefix.size} prefixes, ${map.wire.length} wire names -> ${out}`);
